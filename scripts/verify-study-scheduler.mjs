/* deterministic tests for the dated self-assessment rules, independent of browser */
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync(new URL('../study-scheduler.js',import.meta.url),'utf8');
const context={Date,Intl,Object,Number,Set,String,Array,TypeError};
runInNewContext(source,context);
const rules=context.EkabStudyScheduler;
assert.ok(rules,'scheduler exported');
const t=s=>new Date(s);
const a={seen:1,selfCorrect:7,selfAttempts:7,streak:7,weak:0};
assert.equal(rules.evaluate(a,t('2026-10-01T12:00:00Z')).studied,false,'old undated streak does not invent review dates');
rules.record(a,'correct',t('2026-10-01T12:00:00Z'));
rules.record(a,'correct',t('2026-10-01T12:10:00Z'));
rules.record(a,'correct',t('2026-10-01T12:20:00Z'));
assert.equal(rules.evaluate(a,t('2026-10-01T13:00:00Z')).studied,false,'same-day tapping cannot count as studied');
assert.equal(rules.isDue(a,t('2026-10-02T12:20:00Z')),false,'third review schedules next 7 days');
rules.record(a,'correct',t('2026-10-02T14:00:00Z'));
assert.equal(rules.evaluate(a,t('2026-10-02T14:00:00Z')).studied,true,'correct recall after 24 hours and another day');
assert.equal(rules.evaluate(a,t('2026-10-02T14:00:00Z')).mastered,false,'not enough days and span for mastery');
rules.record(a,'correct',t('2026-10-10T12:00:00Z'));
assert.equal(rules.evaluate(a,t('2026-10-10T12:00:00Z')).mastered,true,'fifth success on third day at least 7 days after first');
assert.equal(rules.isDue(a,t('2026-11-09T12:00:00Z')),true,'due review after 30 days');
rules.record(a,'incorrect',t('2026-10-11T12:00:00Z'));
assert.equal(rules.evaluate(a,t('2026-10-11T12:00:00Z')).studied,false,'wrong resets current learning state');
assert.equal(rules.isDue(a,t('2026-10-11T12:01:00Z')),true,'incorrect prioritizes immediate review');
assert.equal(a.selfCorrect,12,'old self-correct totals preserved');
const b={seen:1,selfCorrect:0,selfAttempts:0,streak:0,weak:0};
rules.record(b,'assisted',t('2026-10-11T12:00:00Z'));
assert.equal(b.selfCorrect,0,'help is not correct');
assert.equal(b.streak,0);
assert.equal(b.weak,1);
rules.markReview(b,t('2026-10-11T12:10:00Z'));
assert.equal(b.selfAttempts,1,'manual review flag is not a grading attempt');
assert.equal(rules.isDue(b,t('2026-10-11T12:11:00Z')),true);
assert.equal(rules.evaluate({seen:1},t('2026-10-11T12:00:00Z')).studied,false);
console.log('OK: spaced practice, mastery, wrong/help, due date, legacy progress preserved.');
