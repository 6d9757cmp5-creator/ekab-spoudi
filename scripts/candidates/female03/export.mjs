import {createServer} from 'node:http';
import {readFile,writeFile} from 'node:fs/promises';
import {extname,join,normalize} from 'node:path';
const {chromium}=await import('file:///C:/Users/Ppdks/ekab-tools/node_modules/playwright/index.mjs');
const tools='C:/Users/Ppdks/ekab-tools',av='C:/Users/Ppdks/ekab-avatar-candidates/rocketbox/Assets/Avatars/Professions/Medical_Female_03';
const out=process.argv[2];
const opts={body:+process.argv[3]||1024,head:+process.argv[4]||2048,headNormal:+process.argv[5]||1024};
const server=createServer(async(q,s)=>{try{const p=decodeURIComponent(new URL(q.url,'http://x').pathname);
 const file=p.startsWith('/avatar/')?join(av,p.slice(8)):p==='/'?join(tools,'conv/export.html'):join(tools,p);
 const b=await readFile(normalize(file));s.writeHead(200,{'content-type':extname(file)==='.html'?'text/html':extname(file)==='.js'||extname(file)==='.mjs'?'text/javascript':'application/octet-stream'});s.end(b);}catch{if(!s.headersSent)s.writeHead(404);s.end();}}).listen(0,'127.0.0.1');
await new Promise(r=>server.once('listening',r));
const b=await chromium.launch({headless:true,channel:'msedge',args:['--ignore-gpu-blocklist']});const p=await b.newPage();
p.on('console',m=>{if(m.type()==='error')console.log('[page]',m.text().slice(0,200));});
await p.goto('http://127.0.0.1:'+server.address().port+'/');await p.waitForFunction(()=>window.ready);
const info=await p.evaluate(async o=>{const r=await window.build(o);window.__o=r.o;return {size:r.size,morphs:r.morphs,sparse:r.sparse,anims:r.o.animations.map(a=>a.name+':'+a.duration.toFixed(2))};},opts);
console.log(JSON.stringify(info));
const scale=info.size[1]>50?0.01:1;
const b64=await p.evaluate(s=>window.exportGlb(s),scale);
await writeFile(out,Buffer.from(b64,'base64'));console.log('wrote',out,Math.round(Buffer.from(b64,'base64').length/1024)+' KB','scale',scale);
await b.close();server.close();
