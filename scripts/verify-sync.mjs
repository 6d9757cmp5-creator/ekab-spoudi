import assert from 'node:assert/strict';
import { SCHEMA, stable, captureEdits, mergeEntries, visibleEntries, validateManifest, DRAFT_SEPARATOR } from '../sync-model.js';
const A='a'.repeat(32),B='b'.repeat(32),C='c'.repeat(32),q='q:EOP-A-001:draft';
const first=captureEdits({}, {}, {[q]:'first'}, A,1);
assert.deepEqual(visibleEntries(mergeEntries({},first)),{[q]:'first'});
const aa=captureEdits(first,{[q]:'first'},{[q]:'from A'},A,2);
const bb=captureEdits(first,{[q]:'first'},{[q]:'from B'},B,3);
const cc=captureEdits(first,{[q]:'first'},{[q]:'from C'},C,4);
assert.equal(stable(mergeEntries(aa,bb)),stable(mergeEntries(bb,aa)));
const merged=mergeEntries(mergeEntries(aa,bb),cc);
assert.equal(stable(merged),stable(mergeEntries(aa,mergeEntries(bb,cc))));
assert.equal(merged[q].v.split(DRAFT_SEPARATOR).length,3);
assert.equal(stable(mergeEntries(merged,merged)),stable(merged));
const explicit=captureEdits(merged,visibleEntries(merged),{[q]:'chosen note'},A,5);
assert.equal(mergeEntries(explicit,first)[q].v,'chosen note');
const removed=captureEdits(explicit,visibleEntries(explicit),{},A,6);
assert.equal(visibleEntries(mergeEntries(removed,first))[q],undefined);
const metric='q:EOP-A-001:seen',base=captureEdits({}, {}, {[metric]:2},A,1);
const left=captureEdits(base,{[metric]:2},{[metric]:4},A,2),right=captureEdits(base,{[metric]:2},{[metric]:3},B,2);
assert.equal(mergeEntries(left,right)[metric].v,4);
const reset=captureEdits(base,{[metric]:2},{},A,3);
assert.equal(mergeEntries(reset,right)[metric].v,3); // Offline progress survives concurrent reset.
const pdf='p:test-pdf',meta={name:'test.pdf',course:'test',semester:'A',created:1,size:10,hash:'f'.repeat(64),fileId:'privatefile'};
const file=captureEdits({}, {}, {[pdf]:meta},A,1),deleted=captureEdits(file,{[pdf]:meta},{},A,2);
assert.deepEqual(deleted[pdf].retired,['privatefile']);
assert.equal(visibleEntries(mergeEntries(deleted,file))[pdf],undefined);
const manifest={schema:SCHEMA,userId:'owner',device:A,entries:merged};
assert.equal(validateManifest(manifest,'owner'),manifest);
assert.throws(()=>validateManifest(manifest,'other'));
assert.throws(()=>validateManifest({...manifest,entries:{cookieFallback:merged[q]}},'owner'));
assert.throws(()=>validateManifest({...manifest,entries:{[q]:{...merged[q],clock:{'__proto__':1}}}},'owner'));
assert.throws(()=>captureEdits({}, {}, {'theme':'<script>bad</script>'},A));
assert.throws(()=>captureEdits({}, {}, {[pdf]:{...meta,fileId:'../../private'}},A));
console.log('Sync model: initial merge, causal edits/deletions, commutative/idempotent note conflict preservation, counter merge, no stale resurrection, owner/schema/key/value validation: passed.');
const history='q:EOP-A-001:reviewHistory',due='q:EOP-A-001:nextReviewAt';
const e1={at:'2026-10-25T10:00:00.000Z',localDay:'2026-10-25',result:'correct'},e2={at:'2026-10-26T10:00:00.000Z',localDay:'2026-10-26',result:'incorrect'};
const h1=captureEdits({}, {}, {[history]:[e1],[due]:'2026-10-28T10:00:00.000Z'},A,1),h2=captureEdits({}, {}, {[history]:[e2],[due]:'2026-10-26T10:00:00.000Z'},B,2);
const hm=mergeEntries(h1,h2);assert.equal(hm[history].v.length,2);assert.equal(hm[due].v,'2026-10-26T10:00:00.000Z');assert.equal(stable(mergeEntries(h1,h2)),stable(mergeEntries(h2,h1)));
assert.throws(()=>captureEdits({}, {}, {[history]:[{...e1,result:'untrusted'}]},A));
console.log('Dated study history and next-review schedule are preserved and merged: passed.');
