/* EOPPEP reader completion regression checks; no clinical assertions. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=file=>readFileSync(new URL('../'+file,import.meta.url),'utf8');
const modelCode=read('sync-model.js').replace(/^import .+\n/gm,'');
const {validValue,captureEdits,mergeEntry,visibleEntries}=await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(modelCode));
const html=read('theory.html'),hub=read('eoppep.html'),app=read('app.js'),hubJs=read('eoppep-hub.js'),local=read('sync-local.js'),model=read('sync-model.js'),styles=read('styles.css');
assert.match(html,/id="catalogReaderMarkRead"/,'Mark as read button missing');
assert.match(html,/id="catalogReaderNext"[\s\S]*?id="catalogReaderMarkRead"/,'Reader completion must be beside next question');
assert.match(html,/id="readCount"/);
assert.match(hub,/id="eopHubReadCount"/);
assert.match(app,/delete progress\.readCompletedAt/,'Mark as read must support undo');
assert.match(app,/progress\.readCompletedAt=new Date\(\)\.toISOString\(\)/);
assert.match(app,/markRead\.setAttribute\('aria-pressed'/);
assert.match(app,/readCount'\)\.textContent/);
assert.match(hubJs,/progress\.read\.all/);
assert.match(styles,/catalogReaderMarkRead\{grid-column:1\/-1/,'Mobile button should span full width');
assert.match(local,/readCompletedAt/);
assert.match(model,/readCompletedAt/);
const key='q:EOP-A-001:readCompletedAt',deviceA='a'.repeat(32),deviceB='b'.repeat(32);
const date='2026-10-28T14:00:00.000Z';
assert.equal(validValue(key,date),true);
assert.equal(validValue(key,'bad date'),false);
assert.equal(validValue(key,null),true);
assert.equal(validValue('q:EOP-A-106:readCompletedAt',date),false);
const writes=captureEdits({}, {}, {[key]:date},deviceA,1);
assert.equal(visibleEntries(writes)[key],date);
const removal=captureEdits(writes,{[key]:date},{},deviceA,2);
assert.equal(visibleEntries(removal)[key],undefined,'Undo must remove visible completion');
const concurrent={v:null,clock:{[deviceB]:1},at:3,writer:deviceB,retired:[]};
assert.equal(mergeEntry(key,writes[key],concurrent).v,null,'Later concurrent undo must win');
const isReadComplete=Boolean(date&&Number.isFinite(Date.parse(date)));
assert.equal(isReadComplete,true);
console.log('✅ EOPPEP reader completion: UI, mobile, undo, sync and progress separated.');
